"""Build the encrypted database for the website in ./site/.

Reads output/*.csv, normalises it into one JSON document, gzips it and encrypts
it with AES-256-GCM using a key derived from the PIN (PBKDF2-SHA256). The PIN is
never written anywhere: pass it via the MEIKAN_PIN environment variable, or type
it at the prompt.

    MEIKAN_PIN=... .venv/bin/python build_site.py
"""
import base64
import csv
import getpass
import gzip
import hashlib
import json
import os
import re
from pathlib import Path

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = Path(__file__).parent
SRC = ROOT / "output"
DEST = ROOT / "site" / "data.enc.js"
ITERATIONS = 600_000
PIN_LENGTH = 15

REGIONS = {
    "北海道・東北": "北海道 青森県 岩手県 宮城県 秋田県 山形県 福島県",
    "北関東": "茨城県 栃木県 群馬県",
    "南関東（東京都以外）": "埼玉県 千葉県 神奈川県",
    "東京都": "東京都",
    "中部": "新潟県 富山県 石川県 福井県 山梨県 長野県 岐阜県 静岡県 愛知県",
    "近畿": "三重県 滋賀県 京都府 大阪府 兵庫県 奈良県 和歌山県",
    "中国": "鳥取県 島根県 岡山県 広島県 山口県",
    "四国": "徳島県 香川県 愛媛県 高知県",
    "九州・沖縄": "福岡県 佐賀県 長崎県 熊本県 大分県 宮崎県 鹿児島県 沖縄県",
}
PREF_REGION = {p: r for r, ps in REGIONS.items() for p in ps.split()}
PREF_ORDER = [p for ps in REGIONS.values() for p in ps.split()]


def read(name):
    with open(SRC / name, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def split(value, sep=r"\s\|\s"):
    return [v.strip() for v in re.split(sep, value or "") if v.strip()]


def writer_record(r):
    genres = []
    for g in split(r["genres"]):
        cat, _, sub = g.rpartition(" > ")
        genres.append([cat, sub])
    portfolio = []
    for p in split(r["portfolio"]):
        label, _, url = p.partition(": ")
        portfolio.append([label, url])
    extra = []
    for e in split(r["other_details"]):
        k, _, v = e.partition(": ")
        extra.append([k.rstrip("：:"), v])
    sns = {k[4:]: split(r[k]) for k in r if k.startswith("sns_") and r[k]}
    pref = r["list_prefecture"]
    return {
        "id": r["writer_id"],
        "name": r["name"],
        "kana": r["kana"],
        "group": r["kana_group"],
        "pref": pref,
        "region": PREF_REGION.get(pref, "海外・その他"),
        "area": r["area"],
        "invoice": bool(r["invoice"]),
        "style": r["work_style"],
        "catch": r["catchcopy"],
        "profile": r["profile"],
        "cats": split(r["genre_categories"]),
        "genres": genres,
        "services": split(r["services"]),
        "apps": split(r["apps"], r"[｜|,、，]"),
        "extra": extra,
        "portfolio": portfolio,
        "sns": sns,
        "contact": r["contact_url"],
        "img": r["profile_image"],
        "tags": split(r["tags"]),
        "url": r["final_url"] or r["url"],
    }


def build_db():
    writers = [writer_record(r) for r in read("writers.csv")]
    tags = [
        {"name": t["tag"], "cat": t["sidebar_category"], "count": int(t["writer_count"])}
        for t in read("tags.csv")
        if t["http_status"] == "200" and int(t["writer_count"]) > 0
    ]
    tags.sort(key=lambda t: (-t["count"], t["name"]))
    return {
        "meta": {
            "source": "https://jobmagazine.jp/meikan/writer/list/",
            "scrapedAt": "2026-10-29",
            "regions": list(REGIONS) + ["海外・その他"],
            "prefOrder": PREF_ORDER,
        },
        "writers": writers,
        "tags": tags,
    }


def encrypt(data: bytes, pin: str) -> dict:
    salt, iv = os.urandom(16), os.urandom(12)
    key = hashlib.pbkdf2_hmac("sha256", pin.encode(), salt, ITERATIONS, dklen=32)
    ct = AESGCM(key).encrypt(iv, data, None)
    b64 = lambda b: base64.b64encode(b).decode()
    return {"v": 1, "kdf": "PBKDF2-SHA256", "iter": ITERATIONS, "pinLength": PIN_LENGTH,
            "salt": b64(salt), "iv": b64(iv), "data": b64(ct)}


def main():
    pin = os.environ.get("MEIKAN_PIN") or getpass.getpass("PIN: ")
    if not re.fullmatch(rf"\d{{{PIN_LENGTH}}}", pin):
        raise SystemExit(f"PIN must be exactly {PIN_LENGTH} digits")
    db = build_db()
    raw = json.dumps(db, ensure_ascii=False, separators=(",", ":")).encode()
    payload = encrypt(gzip.compress(raw, 9), pin)
    DEST.parent.mkdir(exist_ok=True)
    DEST.write_text(
        "/* Encrypted database (AES-256-GCM, PBKDF2-SHA256). Generated by build_site.py. */\n"
        f"window.MEIKAN_VAULT={json.dumps(payload)};\n",
        encoding="utf-8",
    )
    print(f"{len(db['writers'])} writers, {len(db['tags'])} tags; "
          f"{len(raw):,} B json -> {DEST.stat().st_size:,} B encrypted at {DEST}")


if __name__ == "__main__":
    main()
